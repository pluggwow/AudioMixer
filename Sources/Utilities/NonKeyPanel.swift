import AppKit

/// Окно, которое не становится ключевым ни при каких обстоятельствах.
///
/// Таких окон в приложении два — панель микшера и окно настроек, — и обоим
/// фокус не нужен: все контролы работают от мыши, полей ввода нет. Зато
/// отсутствие фокуса снимает целый класс проблем: панель не закрывается,
/// когда нажали что-то в настройках, а приложение не выходит на передний
/// план при клике по значку в менюбаре.
///
/// `becomesKeyOnlyIfNeeded` здесь не годится: контрол, которому фокус нужен,
/// всё равно его запросит — не при каждом клике, поэтому и выглядит
/// случайностью.
final class NonKeyPanel: NSPanel {
    override var canBecomeKey: Bool { false }
    override var canBecomeMain: Bool { false }
}
